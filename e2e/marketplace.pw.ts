test('saves teacher sections atomically and retains edits after a failed save', async ({ page, run }) => {
  await signIn(page, run.teacherAccount)
  await page.goto('/teacher/onboarding')
  await page.getByRole('button', { name: /הצגה מקצועית/ }).click()
  const headline = `פרופיל מעודכן ${run.id.slice(0, 6)}`
  await page.getByLabel('כותרת מקצועית', { exact: true }).fill(headline)
  await page.getByRole('button', { name: 'שמירת שינויים', exact: true }).click()
  await expect(page.getByText('השינויים נשמרו.', { exact: true })).toBeVisible()
  await expect.poll(async () => (await run.db.from('teacher_profiles').select('headline').eq('id', run.teacher.id).single()).data?.headline).toBe(headline)
  await page.getByLabel('כותרת מקצועית', { exact: true }).fill('עריכה שנותרת אחרי כשל')
  await page.route('**/api/teachers/me/profile', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Controlled save failure' }) }))
  await page.getByRole('button', { name: 'שמירת שינויים', exact: true }).click()
  await expect(page.getByRole('alert').first()).toContainText('לא התקבל אישור שמירה')
  await expect(page.getByLabel('כותרת מקצועית', { exact: true })).toHaveValue('עריכה שנותרת אחרי כשל')
  expect((await run.db.from('teacher_profiles').select('headline').eq('id', run.teacher.id).single()).data?.headline).toBe(headline)
  await page.unroute('**/api/teachers/me/profile')
  await page.getByRole('button', { name: 'שמירת שינויים', exact: true }).click()
  await expect(page.getByText('השינויים נשמרו.', { exact: true })).toBeVisible()
  const invalid = await api(page, 'PUT', '/teachers/me/profile', { ...run.form, firstName: 'Must not persist', subjectSlugs: ['missing-subject'], submitForReview: false })
  expect(invalid.status).toBe(400)
  expect((await run.db.from('profiles').select('first_name').eq('id', run.teacherAccount.id).single()).data?.first_name).toBe('UX')
})

